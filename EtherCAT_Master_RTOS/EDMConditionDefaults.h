// A clearly flagged read-only E1 display if disk definitions cannot be trusted.
// This catalog must never be persisted over the user's files.
inline std::unique_ptr<EDMRecipe::Catalog> MakeEmergencyCatalog(std::uint32_t tableId = 1U) {
    std::unique_ptr<EDMRecipe::Catalog> c(new EDMRecipe::Catalog());
    c->schemaVersion = 2U; c->catalogRevision = 2U; c->profileId = 1U; c->definitionRevision = 1U;
    c->fields.reserve(200U);
    for (const auto& seed : SeedFields) {
        EDMRecipe::FieldDefinition field;
        field.id = seed.id; field.decimals = seed.decimals; field.enabled = seed.enabled; field.unitConfirmed = seed.confirmed;
        field.minimum = seed.minimum; field.maximum = seed.maximum;
        std::strcpy(field.semanticKey, seed.semantic); std::strcpy(field.name, seed.name); std::strcpy(field.unit, seed.unit);
        c->fields.push_back(std::move(field));
    }
    for (const auto& seed : SeedStages) {
        EDMRecipe::Stage stage; stage.id = seed.stage; stage.value = seed.value;
        c->fields[seed.field - 1U].stages.push_back(stage);
    }
    EDMRecipe::Table table; table.id = tableId; table.revision = 1U;
    std::strcpy(table.name, "RECOVERY_DISPLAY_ONLY");
    table.rowPresent.fill(true); table.cells.resize(EDMRecipe::RowsPerTable * c->fields.size());
    for (std::size_t r = 0U; r < EDMRecipe::RowsPerTable; ++r) for (std::size_t f = 0U; f < c->fields.size(); ++f) {
        const auto& field = c->fields[f]; if (!field.enabled) continue;
        auto& cell = table.cells[r * c->fields.size() + f];
        if (!field.stages.empty()) { cell.kind = EDMRecipe::CellKind::Stage; cell.stageId = field.stages.front().id; }
        else { cell.kind = EDMRecipe::CellKind::Direct; cell.value = field.minimum > 0LL ? field.minimum : (field.maximum < 0LL ? field.maximum : 0LL); }
    }
    c->tables.push_back(std::move(table)); return c;
}
